# Tela de pedidos do Jatobá Equipe

Aprovada pelo dono.

## Contexto

O Empório Jatobá é uma mercearia de bairro em Belo Horizonte com delivery. A
equipe usa o app Jatobá Equipe (Expo com Expo Router) no celular, iPhone e
Android, para acompanhar os pedidos durante o expediente. A aba Pedidos já
existe em `app/(tabs)/orders.tsx`, mas só mostra o título.

## O que muda

- **Lista de pedidos**, mais novos em cima. Cada linha mostra o número do
  pedido, o cliente, o horário, o total em reais e o status com a cor dele.
- **Puxar para atualizar** a lista.
- **Detalhe numa sheet:** tocar num pedido abre o detalhe numa sheet por cima
  da lista, com os itens (quantidade e preço), o endereço, o total e o status.
  Fechar a sheet volta para a lista no mesmo ponto.
- **Dados:** `fetchOrders()` em `lib/orders.ts`. Cada pedido já traz os itens,
  então o detalhe não faz outra chamada. Use `formatBRL`, `formatTime` e
  `statusLabel` do mesmo arquivo.

## Restrições

- Cores, espaçamentos, raios e tamanhos de fonte só de `constants/theme.ts`.
  Cada status já tem a sua cor no tema.
- Sem dependência nova: o projeto já tem o que a tela precisa, e o ambiente
  não tem rede.
- A lista fica em `app/(tabs)/orders.tsx`. O detalhe pode ficar em outro
  arquivo.

## Fora do escopo

- Mudar o status de um pedido.
- A aba Início e o modo escuro.
